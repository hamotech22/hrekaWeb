export function translateContent(collection, item, lang) {
  if (lang !== "ar" || collection !== "blogs") return item;
  const translation = blogTranslations[item.id];
  if (!translation) return item;

  const localized = { ...item, ...translation };
  if (item.author && translation.authorRole) {
    localized.author = { ...item.author, role: translation.authorRole };
  }
  return localized;
}
